"""Baixa e prepara uma amostra de código de cada linguagem.

Para cada linguagem:
1. baixa ~10 mil arquivos para ``data/<dataset>/raw/<lang>.jsonl``: o arquivo
   inteiro do bigcode/the-stack-smol-xl, ou uma amostra do primeiro shard do
   bigcode/the-stack-dedup (JSON e YAML, que não existem no smol-xl);
2. aplica filtros de qualidade inspirados no StarCoder e padroniza o texto
   (``codelm.indentation.normalize_code``: quebras de linha, tabs da
   indentação, quebra de linha final);
3. remove duplicatas exatas;
4. separa treino/validação por repositório (o mesmo repo nunca aparece nos dois)
   e salva em ``data/code-language-model/processed/<lang>/{train,valid}.parquet``.

Uso:
    uv run python -m dataprep.download                 # todas as linguagens
    uv run python -m dataprep.download python rust     # apenas algumas
"""

import argparse
import ast
import hashlib
import json
import random
import re
import shutil
import warnings
from collections import Counter
from pathlib import Path

import pyarrow as pa
import pyarrow.parquet as pq
from huggingface_hub import HfApi, hf_hub_download

from codelm.indentation import has_mixed_indentation, has_odd_indentation, normalize_code
from codelm.languages import DATA_DIR, LANGUAGES
from dataprep.corpus import PROCESSED_DIR

SOURCES = {
    "the-stack-smol-xl": "bigcode/the-stack-smol-xl",
    "the-stack-dedup": "bigcode/the-stack-dedup",
}
SAMPLE_SIZE = 10_000
RAW_FIELDS = ("content", "ext", "max_stars_repo_name", "max_stars_repo_path", "max_stars_repo_licenses")

VALID_FRACTION = 0.02
MIN_CHARS = 20
MAX_CHARS = 200_000
MAX_LINE_LENGTH = 1000
MAX_MEAN_LINE_LENGTH = 100
MIN_ALNUM_FRACTION = 0.25
GENERATED_MARKERS = ("auto-generated", "autogenerated", "automatically generated", "generated by", "do not edit")
# Arquivos gerados por gerenciadores de pacote: enormes e sem valor como exemplo.
LOCK_FILES = {"package-lock.json", "composer.lock", "npm-shrinkwrap.json", "pnpm-lock.yaml"}
# Headers .h de Objective-C/C++ que aparecem misturados na pasta de C do The Stack.
NOT_C_PATTERN = re.compile(r"^\s*(#import\b|@interface\b|@protocol\b|class\s+\w+\s*[:{]|namespace\s+\w+|template\s*<)", re.M)


def download(lang: str) -> Path:
    language = LANGUAGES[lang]
    target = DATA_DIR / language.source / "raw" / f"{lang}.jsonl"
    if target.exists():
        return target
    target.parent.mkdir(parents=True, exist_ok=True)
    repo = SOURCES[language.source]

    if language.source == "the-stack-smol-xl":
        cached = hf_hub_download(repo, f"data/{language.stack_dir}/data.json", repo_type="dataset")
        shutil.copyfile(cached, target)
        return target

    # the-stack-dedup: shards parquet de ~150 MB; um basta para a amostra.
    prefix = f"data/{language.stack_dir}/"
    shard = min(f for f in HfApi().list_repo_files(repo, repo_type="dataset") if f.startswith(prefix))
    table = pq.read_table(hf_hub_download(repo, shard, repo_type="dataset"), columns=list(RAW_FIELDS))
    rows = table.to_pylist()
    sample = random.Random(0).sample(rows, min(SAMPLE_SIZE, len(rows)))
    with target.open("w") as f:
        for row in sample:
            f.write(json.dumps(row) + "\n")
    return target


def rejection_reason(content: str, lang: str) -> str | None:
    """Retorna o motivo da rejeição, ou None se o arquivo passa nos filtros."""
    if content.startswith("version https://git-lfs"):
        return "ponteiro do git-lfs"
    if not MIN_CHARS <= len(content) <= MAX_CHARS:
        return "tamanho"
    lines = content.splitlines() or [""]
    if max(map(len, lines)) > MAX_LINE_LENGTH:
        return "linha longa"
    if len(content) / len(lines) > MAX_MEAN_LINE_LENGTH:
        return "média de linha"
    if sum(ch.isalnum() for ch in content) / len(content) < MIN_ALNUM_FRACTION:
        return "pouco alfanumérico"
    head = "\n".join(lines[:5]).lower()
    if any(marker in head for marker in GENERATED_MARKERS):
        return "gerado automaticamente"
    if lang == "c" and NOT_C_PATTERN.search(content):
        return "não é C (Objective-C/C++)"
    return None


def is_valid_split(repo: str) -> bool:
    bucket = int(hashlib.sha256(repo.encode()).hexdigest(), 16) % 10_000
    return bucket < VALID_FRACTION * 10_000


def compiles_as_python3(content: str) -> bool:
    """Se o código é Python 3 válido (sintaxe), pelo parser do próprio Python."""
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")  # avisos de escapes inválidos em strings antigas
            ast.parse(content)
    except (SyntaxError, ValueError):
        return False
    return True


def clean_file(row: dict, lang: str, seen: set[str], stats: Counter) -> dict | None:
    """Filtra e padroniza um arquivo do The Stack; None se rejeitado (motivo em ``stats``).

    ``seen`` guarda os hashes já aceitos, para remover duplicatas exatas.
    """
    content = row["content"]
    stats["lidos"] += 1
    path = row.get("max_stars_repo_path") or ""
    if path.rsplit("/", 1)[-1] in LOCK_FILES:
        stats["rejeitado: arquivo de lock"] += 1
        return None
    # Em Python os blocos dependem da indentação: com tabs e espaços
    # misturados, a conversão poderia mudar o significado.
    if lang == "python" and has_mixed_indentation(content):
        stats["rejeitado: tabs e espaços misturados"] += 1
        return None
    content = normalize_code(content)
    # Blocos com recuo ímpar (1 ou 3 espaços) não cabem na unidade de 2 da
    # indentação relativa, e a gramática de Python do sampler não os aceita.
    if lang == "python" and has_odd_indentation(content, lang):
        stats["rejeitado: indentação ímpar"] += 1
        return None
    if reason := rejection_reason(content, lang):
        stats[f"rejeitado: {reason}"] += 1
        return None
    # Python 2 e código quebrado: o modelo aprenderia sintaxe que a gramática do
    # sampler bloqueia na geração.
    if lang == "python" and not compiles_as_python3(content):
        stats["rejeitado: não compila em Python 3"] += 1
        return None
    digest = hashlib.sha256(content.strip().encode()).hexdigest()
    if digest in seen:
        stats["rejeitado: duplicado"] += 1
        return None
    seen.add(digest)

    repo = row.get("max_stars_repo_name") or ""
    return {
        "content": content,
        "lang": lang,
        "ext": row.get("ext"),
        "repo": repo,
        "path": path,
        "licenses": row.get("max_stars_repo_licenses") or [],
        "sha256": digest,
        "split": "valid" if is_valid_split(repo) else "train",
    }


def prepare(lang: str, raw_path: Path) -> Counter:
    stats = Counter()
    seen: set[str] = set()
    splits: dict[str, list[dict]] = {"train": [], "valid": []}

    with raw_path.open() as f:
        for line in f:
            if file := clean_file(json.loads(line), lang, seen, stats):
                splits[file.pop("split")].append(file)
    stats.update({split: len(rows) for split, rows in splits.items()})

    out_dir = PROCESSED_DIR / lang
    out_dir.mkdir(parents=True, exist_ok=True)
    for split, rows in splits.items():
        pq.write_table(pa.Table.from_pylist(rows), out_dir / f"{split}.parquet")
        stats[f"chars {split}"] = sum(len(r["content"]) for r in rows)
    return stats


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("languages", nargs="*", help=f"padrão: todas ({', '.join(LANGUAGES)})")
    args = parser.parse_args()
    if unknown := set(args.languages) - set(LANGUAGES):
        parser.error(f"linguagens desconhecidas: {', '.join(sorted(unknown))}")

    for lang in args.languages or LANGUAGES:
        print(f"== {lang}")
        stats = prepare(lang, download(lang))
        for key, value in sorted(stats.items()):
            print(f"  {key:<32} {value:>12,}")


if __name__ == "__main__":
    main()
